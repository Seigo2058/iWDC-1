"""Request / response models for search (RAG)."""

from pydantic import BaseModel, Field


class SearchRequest(BaseModel):
    query: str = Field(min_length=1, description="Search query")
    top_k: int = Field(default=5, ge=1, le=50, description="Number of similar chunks to retrieve")


class SearchHit(BaseModel):
    document_id: str
    chunk_id: str
    text: str
    score: float = Field(description="Similarity score (higher is closer)")


class SearchResponse(BaseModel):
    query: str
    hits: list[SearchHit]
    answer: str | None = Field(default=None, description="Answer generated by RAG")
